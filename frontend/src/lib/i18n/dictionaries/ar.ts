/**
 * # The Arabic word for each thing, chosen once
 *
 * Gradex had two Arabic words for its central object. The Student surfaces, the landing page, the
 * catalogue and the navigation said **مقرر**; the Admin, Instructor and Course-detail copy said
 * **دورة**. There is only one Course in this product — one object, one contract, one lifecycle — so
 * two words for it was drift between tranches, not a distinction the domain makes.
 *
 * **مقرر** is the word. It is the registrar's term for a university course, it is what the product
 * already promises on its own landing page ("مقررات جامعية لطلبة الخليج"), and it sits correctly
 * beside **مادة** (Subject), which is the academic thing a Course is taught *for*. **دورة** is the
 * training-course register — a short course, a bootcamp — and Gradex does not sell those. The one
 * surviving `دورة` is in "دورة حياة المقرر", where the word means *cycle* and is a different word.
 *
 * The same audit found two more:
 *
 *  - Instructor was **مدرّب** in the Admin Courses block and **مدرّس** everywhere else. مدرّب is a
 *    trainer, from the same register as دورة. **مدرّس** is the word.
 *  - Student was **الطلاب** in three places and **الطلبة** in sixteen. Both are correct Arabic and
 *    only one of them can be the product's: **الطلبة**.
 *
 * The settled vocabulary, by concept:
 *
 * | Concept              | Arabic                        |
 * | -------------------- | ----------------------------- |
 * | Course               | مقرر                          |
 * | Subject              | مادة                          |
 * | Lesson               | درس                           |
 * | Section              | قسم                           |
 * | Program / Major      | تخصص                          |
 * | Institution          | جامعة                         |
 * | College              | كلية                          |
 * | Academic level       | المستوى الدراسي               |
 * | Instructor           | مدرّس                         |
 * | Student              | طالب / الطلبة                 |
 * | Administrator        | مشرف                          |
 * | Access               | الوصول                        |
 * | Review               | مراجعة                        |
 * | Invitation           | دعوة                          |
 *
 * `parity.test.ts` holds the retired words out, so the next block of copy cannot quietly
 * reintroduce one.
 */
